# Adds small-page reasons and cross-page pointers to page-manifest.json and writes ../../page-manifest.md
import json,re,collections,sys
sys.path.insert(0,'../e15')
import e15
man=json.load(open('page-manifest.json'))
SMALL={'credential':'own domain, facade and commands (add-credential)','model-defaults':'own domain; users set defaults per cloud and region','upgrade':'mechanism: controller upgrade state across nodes',
 'ssh-key':'users address it directly (add-ssh-key, import-ssh-key)','agent-version':'users address it through upgrade commands; tiny but cross-cutting with binaries','space':'users address it (spaces, move-to-space)','zone':'users address it as a constraint and in status',
 'lease':'mechanism: leadership and leases','image-metadata':'own domain and plugin commands (juju-metadata)','permission':'own page (access levels), grant and revoke commands','block-command':'mechanism: disable-command and enable-command',
 'removal':'mechanism: scheduled removal jobs (the removing-things page)','port':'users and charms address it (open-port, close-port)','status':'facet page across entities; owns only the shared status vocabulary, each entity page owns its status table'}
for p,r in SMALL.items(): man['pages'][p]['small_reason']=r
S=('model','controller'); V={s:e15.parse(e15.NEW[s]) for s in S}
body={}
for s in S:
    for t,b in V[s]['tables'].items(): body[t]=body.get(t,'')+' '+b
home={t:p for p,d in man['pages'].items() for t in d['tables']}
att=collections.defaultdict(set)
for t,p in home.items():
    for q in set(re.findall(r'REFERENCES\s+"?(\w+)',body[t]))-{t}:
        if q in home and home[q]!=p: att[p].add((t,q,home[q]))
for p,d in man['pages'].items(): d['points_to']=sorted({f'{t} -> {q} ({hp})' for t,q,hp in att.get(p,[])})
json.dump(man,open('page-manifest.json','w'),indent=1)
L=['# Page manifest (hypothesis E34, version 2, generated, 4.1, session 79)','','Every non-lookup table of both schemas has exactly one home page. Shared lookups belong to no page. Association tables (a table that links two nouns) have one home and are shown on the other page by a pointer. Generated by `experiments/e33/manifest.py` and `render_manifest.py` from first-word defaults plus reviewed overrides (reasons in `page-manifest.json`); the falsification tests M1 to M6 and the changes made after them are in `structure-discovery-plan.md` (E34).','']
L.append('| page | kind | tables | lookups owned | points to (other pages) |'); L.append('|---|---|---|---|---|')
for p,d in sorted(man['pages'].items(),key=lambda x:-len(x[1]['tables'])):
    pt=sorted({x.split('(')[-1].rstrip(')') for x in d['points_to']})
    L.append(f"| **{p}** | {d['kind']} | {len(d['tables'])} | {len(d['lookups'])} | {', '.join(pt)} |")
L+=['','## Tables by page','']
for p,d in sorted(man['pages'].items(),key=lambda x:-len(x[1]['tables'])):
    L.append(f"### {p} ({d['kind']})"); L.append(d['about'])
    if d.get('small_reason'): L.append(f"*Small page: {d['small_reason']}.*")
    L.append(''); L.append('Tables: '+(', '.join(f'`{t}`' for t in d['tables']) if d['tables'] else '(none; the page points to tables on entity pages)'))
    if d['lookups']: L.append(''); L.append('Lookups: '+', '.join(f'`{t}`' for t in d['lookups']))
    if d['points_to']: L.append(''); L.append('Points to: '+'; '.join(d['points_to'][:12])+(' ...' if len(d['points_to'])>12 else ''))
    L.append('')
L+=['## Shared vocabulary (belongs to no page)','',', '.join(f'`{t}`' for t in man['shared_vocabulary']),'']
open('../../page-manifest.md','w').write('\n'.join(L))
print('written',len(L),'lines')
